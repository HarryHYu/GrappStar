def spur_gear(m, z, face, pa=20.0, shift=0.0, backlash=fits.GEAR_BACKLASH, root_fillet=True, bore=None,
              bore_kind="round", bore_opts=None, hub=None, chamfer=0.5, present=None, tip_short=0.0, seg=None):
    """External involute spur gear. Frame: axis +Z, face z = 0..face, tooth 0 on +X.
    m module (mm), z teeth, pa pressure angle (deg), shift profile shift coefficient x, backlash (mm, each gear thins
    by backlash / 2 at the pitch circle), tip_short tip shortening coefficient k (ra reduced by k m), bore hole
    diameter (see bore_cs for bore_kind and bore_opts), hub (d, h) boss on top from z = face to face + h (keep d
    under the root diameter), chamfer tip edge chamfer (mm), present tooth indices to keep (partial gear, other
    teeth removed down to the root circle)."""
    inf = spur_info(m, z, shift, pa, backlash, tip_short)
    land = inf["s_tip"]
    if inf["pointed"] or not land == land or land < MIN_TIP_LAND:
        warnings.warn(f"spur_gear m{m:g} z{z} shift {shift:g}: pointed teeth (tip land {land:.2f} mm, need >= "
                      f"{MIN_TIP_LAND:g} mm for the 0.4 nozzle and >= 0.25 m); reduce shift or use tip_short",
                      stacklevel=2)
    g2 = spur_profile(m, z, pa, shift, backlash, root_fillet, present, tip_short, seg)
    body = prim.extrude(prim.shapely_cs(g2), face)
    ra = inf["r_tip"]
    return _finish(body, ra, face, chamfer, hub, bore, bore_kind, bore_opts)


def internal_gear(m, z, face, rim_od, pa=20.0, shift=0.0, backlash=fits.GEAR_BACKLASH, chamfer=0.3, seg=None):
    """Internal (ring) gear, teeth pointing inwards. Frame: axis +Z, face z = 0..face, a tooth SPACE centred on +X.
    Tooth spaces are the teeth of a rack-generated external gear with tip radius r + 1.25 m and tooth thickness
    pi m / 2 + backlash / 2 (ring teeth thinned by backlash / 2); ring tip (inner) radius r - (1 - shift) m.
    Positive shift moves the profile outwards (away from the axis). Pair with internal_center_distance."""
    r = m * z / 2
    ri = r - (HA - shift) * m
    space = spur_profile(m, z, pa, shift, -backlash, True, None, tip_short=-(HF - HA), seg=seg)
    ro = rim_od / 2
    if ro < r + (HF + shift) * m + 1.0:
        raise ValueError("rim_od too small for the ring gear")
    ring2 = _circle(ro, prim.segs(ro)).difference(space.union(_circle(ri, max(prim.segs(ri), 8 * z))))
    body = prim.extrude(prim.shapely_cs(ring2), face)
    if chamfer and chamfer > 0:
        c = min(chamfer, face / 2 - 1e-3)
        e = 0.3 + c
        pts = [(ri + c, -0.01), (ri - e, c + e), (ri - e, face - c - e), (ri + c, face + 0.01)]
        nc = max(prim.segs(ri), 96)
        cone = prim.revolve_pts([(ri + c, -1)] + pts + [(ri + c, face + 1), (ri - e - 1, face + 1), (ri - e - 1, -1)],
                                seg=nc).rotate((0, 0, _CONE_PHASE * 360.0 / nc))
        body = body - cone
    return body


def internal_info(m, z, shift=0.0, pa=20.0):
    """Ring gear radii (mm): pitch, base, tip (inner), root (outer)."""
    r = m * z / 2
    return {"r_pitch": r, "r_base": r * math.cos(math.radians(pa)), "r_tip": r - (HA - shift) * m,
            "r_root": r + (HF + shift) * m}


def rack_profile(m, n_teeth, body_h, pa=20.0, backlash=fits.GEAR_BACKLASH, fillet=0.25):
    """2D rack outline (shapely). Pitch line y = 0, teeth point -y, tooth k centred at x = (k + 0.5) pi m,
    x from 0 to n_teeth pi m, root line y = 1.25 m, back face at y = 1.25 m + body_h."""
    a = math.radians(pa)
    ta = math.tan(a)
    p = math.pi * m
    h0 = (p / 2 - backlash / 2) / 2
    ytip, yroot = -HA * m, HF * m
    rho = fillet * m

    def half(y):
        return h0 + y * ta                # half thickness at height y (wider towards the root)

    # one period from gap centre x = 0 to x = p (tooth centred at p / 2): root fillet both sides
    pts = []
    if rho > 0:
        # fillet tangent to root line (y = yroot) and flank; centre below the root line, in the gap
        yc = yroot - rho
        # flank line: u = half(y) measured from tooth centre; distance from (uc, yc) to flank = rho, uc > half(yc)
        uc = half(yc) + rho / math.cos(a)
        arc = [(uc + rho * math.cos(t), yc + rho * math.sin(t))
               for t in np.linspace(math.pi / 2, math.pi - a, 7)]        # from root tangent down to flank tangent
        # arc is on the +u side of the tooth (right flank); convert to period coordinates
        right_root = [(p / 2 + u, y) for u, y in arc]
        left_root = [(p / 2 - u, y) for u, y in arc]
    else:
        right_root = [(p / 2 + half(yroot), yroot)]
        left_root = [(p / 2 - half(yroot), yroot)]
    tip = [(p / 2 - half(ytip), ytip), (p / 2 + half(ytip), ytip)]
    period = [(0.0, yroot)] + left_root + tip + right_root[::-1] + [(p, yroot)]
    out = []
    for k in range(n_teeth):
        out += [(x + k * p, y) for x, y in period[:-1]]
    out.append((n_teeth * p, yroot))
    ytop = yroot + body_h
    out += [(n_teeth * p, ytop), (0.0, ytop)]
    return Polygon(out)


def rack(m, n_teeth, face, body_h, pa=20.0, backlash=fits.GEAR_BACKLASH, fillet=0.25):
    """Straight rack. Frame: teeth along +X (tooth k centred at x = (k + 0.5) pi m), pitch line y = 0, teeth point -y,
    root line y = 1.25 m, back at y = 1.25 m + body_h, extruded z = 0..face. Teeth thinned by backlash / 2.
    A gear meshes with its axis at y = -(r + x m + fits.GEAR_CENTER_EXTRA)."""
    return prim.extrude(prim.shapely_cs(rack_profile(m, n_teeth, body_h, pa, backlash, fillet)), face)


def rack_center_distance(m, z, x=0.0, extra=fits.GEAR_CENTER_EXTRA):
    """Distance (mm) from the rack pitch line to the axis of a meshing gear."""
    return m * z / 2 + x * m + extra
