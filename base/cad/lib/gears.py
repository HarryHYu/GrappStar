"""Involute spur gears, internal (ring) gears and racks, plus gear math and a Lewis strength check.

Units mm, degrees (pa in degrees), N, Nm. Gear frame: axis +Z, face from z = 0 to z = face, centred on the origin,
tooth 0 centred on +X (tooth k at k * 360 / z degrees). Profiles are generated by simulating a basic rack cutter
(addendum 1.25 m, tip radius ~0.38 m) rolling on the pitch circle and differencing its swept area from the blank
(shapely), so the flank is the true involute, the root is the true trochoid and low tooth counts get the real
undercut. Backlash is split: each gear thins its teeth by backlash / 2 (arc at the pitch circle).
"""
from __future__ import annotations

import math
import warnings

import numpy as np
from shapely import affinity
from shapely.geometry import Point, Polygon, box as sbox
from shapely.ops import unary_union

from . import fits, prim

# shared constants (new here)
ALLOW_PLA = 15.0          # MPa, design bending stress for printed PLA teeth (Lewis)
ALLOW_PPA_CF = 35.0       # MPa, design bending stress for printed PPA-CF teeth (Lewis)
ROOT_FILLET = 0.38        # cutter tip radius as a fraction of m (gives the root fillet)
HF = 1.25                 # dedendum coefficient (cutter addendum)
HA = 1.0                  # addendum coefficient
MIN_TIP_LAND = 0.4        # mm, smallest printable tooth tip land (0.4 nozzle); spur_gear warns below it

# Lewis form factor Y (20 deg full depth, load at tip), by tooth count
_LEWIS = [(8, 0.180), (10, 0.201), (12, 0.245), (13, 0.261), (14, 0.277), (15, 0.290), (16, 0.296), (17, 0.303),
          (18, 0.309), (19, 0.314), (20, 0.322), (21, 0.328), (22, 0.331), (24, 0.337), (26, 0.346), (28, 0.353),
          (30, 0.359), (34, 0.371), (38, 0.384), (43, 0.397), (50, 0.409), (60, 0.422), (75, 0.435), (100, 0.447),
          (150, 0.460), (300, 0.472), (100000, 0.485)]


# ---------------------------------------------------------------- math

def inv(a_rad):
    """Involute function tan(a) - a (radians)."""
    return math.tan(a_rad) - a_rad


def inv_inverse(v):
    """Inverse involute: a (radians) with inv(a) = v (Newton)."""
    a = (3 * v) ** (1 / 3) if v > 0 else 0.0
    for _ in range(50):
        f = inv(a) - v
        a -= f / (math.tan(a) ** 2)
        if abs(f) < 1e-15:
            break
    return a


def spur_info(m, z, shift=0.0, pa=20.0, backlash=0.0, tip_short=0.0):
    """Derived numbers of an external spur gear (mm, deg). Thicknesses are arc lengths."""
    a = math.radians(pa)
    r = m * z / 2
    rb = r * math.cos(a)
    ra = r + (HA + shift - tip_short) * m
    rf = r + (shift - HF) * m
    s = math.pi * m / 2 + 2 * shift * m * math.tan(a) - backlash / 2
    # tip thickness
    if ra > rb:
        aa = math.acos(rb / ra)
        sa = 2 * ra * (s / (2 * r) + inv(a) - inv(aa))
    else:
        sa = float("nan")
    z_min = 2 * HA / math.sin(a) ** 2
    return {"m": m, "z": z, "pa": pa, "shift": shift, "r_pitch": r, "r_base": rb, "r_tip": ra, "r_root": rf,
            "d_pitch": 2 * r, "d_tip": 2 * ra, "d_root": 2 * rf, "pitch": math.pi * m,
            "s_pitch": s, "s_tip": sa, "pointed": bool(sa < 0.25 * m) if sa == sa else True,
            "z_min_no_undercut": z_min, "x_min_no_undercut": HA - z * math.sin(a) ** 2 / 2,
            "undercut": bool(shift < HA - z * math.sin(a) ** 2 / 2 - 1e-9)}


def working_pressure_angle(z1, z2, x1=0.0, x2=0.0, pa=20.0):
    """Working pressure angle (deg) of a shifted external pair from inv(aw) = inv(a) + 2 tan(a) (x1 + x2) / (z1 + z2)."""
    a = math.radians(pa)
    return math.degrees(inv_inverse(inv(a) + 2 * math.tan(a) * (x1 + x2) / (z1 + z2)))


def center_distance(m, z1, z2, x1=0.0, x2=0.0, pa=20.0, extra=fits.GEAR_CENTER_EXTRA):
    """Centre distance (mm) of an external pair: m (z1 + z2) / 2 * cos(a) / cos(aw) + extra (fits.GEAR_CENTER_EXTRA)."""
    aw = math.radians(working_pressure_angle(z1, z2, x1, x2, pa))
    return m * (z1 + z2) / 2 * math.cos(math.radians(pa)) / math.cos(aw) + extra


INTERNAL_MIN_DIFF = 10     # minimum z_ring - z_pinion of an unshifted 20 deg internal pair (tip interference)


def internal_working_pressure_angle(z_ring, z_pinion, x_ring=0.0, x_pinion=0.0, pa=20.0):
    """Working pressure angle (deg) of an internal pair from inv(aw) = inv(a) + 2 tan(a) (x2 - x1) / (z2 - z1),
    x2 = x_ring (positive moves the ring profile outwards, as internal_gear's shift), x1 = x_pinion."""
    a = math.radians(pa)
    return math.degrees(inv_inverse(inv(a) + 2 * math.tan(a) * (x_ring - x_pinion) / (z_ring - z_pinion)))


def check_internal_pair(z_ring, z_pinion, x_ring=0.0, x_pinion=0.0, pa=20.0):
    """Raise ValueError when an internal pair has tip (trochoid) interference: with unshifted 20 deg teeth the
    tooth tips of ring and pinion collide when z_ring - z_pinion < INTERNAL_MIN_DIFF (10). A positive
    x_ring - x_pinion (larger working pressure angle) is required for smaller differences: the check then asks for
    a working pressure angle of at least 20 + 2 deg per missing tooth (conservative, verify the mesh)."""
    diff = z_ring - z_pinion
    if diff <= 0:
        raise ValueError(f"internal pair needs z_ring > z_pinion (got {z_ring} and {z_pinion})")
    if diff >= INTERNAL_MIN_DIFF:
        return
    aw = internal_working_pressure_angle(z_ring, z_pinion, x_ring, x_pinion, pa)
    need = 20.0 + 2.0 * (INTERNAL_MIN_DIFF - diff)
    if pa < 20.0 - 1e-9 or aw < need - 1e-9:
        raise ValueError(
            f"internal gear interference: z_ring - z_pinion = {diff} < {INTERNAL_MIN_DIFF} with working pressure "
            f"angle {aw:.1f} deg (tooth tips of ring and pinion collide); use a tooth difference of at least "
            f"{INTERNAL_MIN_DIFF}, or shift the ring outwards (x_ring - x_pinion > 0) to reach aw >= {need:.1f} deg")


def internal_center_distance(m, z_ring, z_pinion, pa=20.0, extra=fits.GEAR_CENTER_EXTRA, x_ring=0.0, x_pinion=0.0):
    """Centre distance (mm) of a pinion inside a ring: m (z_ring - z_pinion) / 2 cos(a) / cos(aw) - extra, aw from
    internal_working_pressure_angle (equal to pa for unshifted gears; x_ring is internal_gear's shift, x_pinion
    spur_gear's). Moving the pinion towards the ring centre opens the backlash, the sign of extra is opposite to
    external pairs. Raises ValueError for pairs with tip interference (see check_internal_pair)."""
    check_internal_pair(z_ring, z_pinion, x_ring, x_pinion, pa)
    aw = math.radians(internal_working_pressure_angle(z_ring, z_pinion, x_ring, x_pinion, pa))
    return m * (z_ring - z_pinion) / 2 * math.cos(math.radians(pa)) / math.cos(aw) - extra


def contact_ratio(m, z1, z2, x1=0.0, x2=0.0, pa=20.0):
    """Transverse contact ratio of an external pair at its working centre distance (no extra). Each gear's share
    sqrt(ra^2 - rb^2) is clamped at the length a sin(aw) of the line of action between the interference points T1, T2
    (contact beyond them is in the mate's undercut / interference zone and does not count)."""
    i1, i2 = spur_info(m, z1, x1, pa), spur_info(m, z2, x2, pa)
    aw = math.radians(working_pressure_angle(z1, z2, x1, x2, pa))
    a_w = center_distance(m, z1, z2, x1, x2, pa, extra=0.0)
    T = a_w * math.sin(aw)
    g1 = min(math.sqrt(i1["r_tip"] ** 2 - i1["r_base"] ** 2), T)
    g2 = min(math.sqrt(i2["r_tip"] ** 2 - i2["r_base"] ** 2), T)
    L = g1 + g2 - T
    return L / (math.pi * m * math.cos(math.radians(pa)))


def lewis_y(z):
    """Lewis form factor Y for z teeth (20 deg full depth), linear interpolation of the standard table."""
    zs, ys = zip(*_LEWIS)
    return float(np.interp(z, zs, ys))


def lewis_stress(m, z, face, torque_nm):
    """Lewis bending stress (MPa) in the teeth of a gear carrying torque_nm: Ft / (face m Y), Ft = T / r.
    Compare with ALLOW_PLA / ALLOW_PPA_CF."""
    ft = torque_nm * 1000.0 / (m * z / 2)
    return ft / (face * m * lewis_y(z))


def lewis_max_torque(m, z, face, allow=ALLOW_PLA):
    """Torque (Nm) at which the Lewis stress reaches allow (MPa)."""
    return allow * face * m * lewis_y(z) * (m * z / 2) / 1000.0


# ---------------------------------------------------------------- profile generation

def _cutter_poly(m, pa, x, bl, r, ra, rho_coef=ROOT_FILLET, hf=HF):
    """One basic-rack cutter tooth (convex polygon) in the gear frame at phi = 0: centred on u = 0, rolling line
    y = r, reference line y = r + x m, tooth pointing -y into the gear. Tooth thickness at the reference line
    pi m / 2 + bl / 2 (so the gear tooth comes out thinner by bl / 2)."""
    a = math.radians(pa)
    ta = math.tan(a)
    yref = r + x * m
    h0 = math.pi * m / 4 + bl / 4
    yt = yref - hf * m
    ytop = max(ra, yref) + 0.6 * m

    def half(y):
        return h0 - (yref - y) * ta

    rho_max = (h0 - hf * m * ta) / (1 / math.cos(a) - ta)
    rho = max(0.0, min(rho_coef * m, 0.98 * rho_max))
    right = []
    if rho > 1e-6:
        yc = yt + rho
        uc = half(yc) - rho / math.cos(a)
        n = 8
        for t in np.linspace(-math.pi / 2, -a, n + 1):
            right.append((uc + rho * math.cos(t), yc + rho * math.sin(t)))
    else:
        right.append((half(yt), yt))
    right.append((half(ytop), ytop))
    left = [(-u, y) for u, y in reversed(right)]
    return Polygon(right + left)


def _gap_poly(m, z, pa, x, bl, ra, tip_r=ROOT_FILLET, hf=HF):
    """Area swept by one cutter tooth through the whole generating motion (gear frame), gap centred at +Y."""
    r = m * z / 2
    cut = _cutter_poly(m, pa, x, bl, r, ra, tip_r, hf)
    y_tip = r + (x - hf) * m
    reach = math.sqrt(max(ra * ra - y_tip * y_tip, 0.0)) + 1.6 * m
    phimax = reach / r
    n = int(max(120, 2 * reach / (0.012 * m)))
    n += (n % 2 == 1)                      # odd count of positions so phi = 0 is included
    phis = np.linspace(-phimax, phimax, n + 1)
    pos = []
    for ph in phis:
        p = affinity.translate(cut, -r * ph, 0)
        pos.append(affinity.rotate(p, -ph, origin=(0, 0), use_radians=True))
    # plain union of dense positions: the envelope is tangent so the scallops are tiny (convex hulls of
    # consecutive positions would over-cut the flank near the cutter top)
    g = unary_union(pos)
    # keep only what is inside the blank (plus margin) to limit vertices
    g = g.intersection(Point(0, 0).buffer(ra + 0.2 * m, 64))
    return g.simplify(0.0005 * m, preserve_topology=True)


def _circle(r, n):
    t = np.linspace(0, 2 * math.pi, n, endpoint=False)
    return Polygon(np.c_[r * np.cos(t), r * np.sin(t)])


def spur_profile(m, z, pa=20.0, shift=0.0, backlash=fits.GEAR_BACKLASH, root_fillet=True, present=None,
                 tip_short=0.0, seg=None):
    """2D external gear outline as a shapely Polygon (gear frame, tooth 0 on +X)."""
    info = spur_info(m, z, shift, pa, backlash, tip_short)
    ra, rf = info["r_tip"], info["r_root"]
    gap = _gap_poly(m, z, pa, shift, backlash, ra, ROOT_FILLET if root_fillet else 0.0)
    gap = affinity.rotate(gap, -90 + 180.0 / z, origin=(0, 0))
    gaps = [affinity.rotate(gap, k * 360.0 / z, origin=(0, 0)) for k in range(z)]
    n = seg or max(prim.segs(ra), 12 * z)
    blank = _circle(ra, n)
    g = blank.difference(unary_union(gaps))
    if present is not None:
        keep = {int(k) % z for k in present}
        rr = ra + m
        cuts = []
        for k in range(z):
            if k in keep:
                continue
            t0 = math.radians((k - 0.5) * 360.0 / z)
            t1 = math.radians((k + 0.5) * 360.0 / z)
            ts = np.linspace(t0, t1, 12)
            wedge = Polygon([(0, 0)] + [(rr * math.cos(t), rr * math.sin(t)) for t in ts])
            cuts.append(wedge)
        if cuts:
            core = _circle(rf, max(prim.segs(rf), 12 * z))
            g = g.difference(unary_union(cuts).difference(core))
    if g.geom_type != "Polygon":
        g = max(g.geoms, key=lambda p: p.area)
    return g


