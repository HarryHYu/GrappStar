"""Printed worm and worm wheel (single or multi start, right hand, 20 deg trapezoidal thread, axial module).

Units mm, degrees. Worm frame: axis +Z, z = 0..length, thread lobe of start 0 on +X at z = 0. Wheel frame: axis +Z,
face z = 0..face, a tooth SPACE centred on +X. The wheel is generated by a simulated hob (a worm with addendum
1.25 m and thread thickened by backlash / 2) rolling with the wheel, so worm and wheel match exactly; throated
gives the concave (enveloping) rim, otherwise a cylindrical blank is hobbed (the classic printed helical
approximation, but with the true flank). worm_pose() places the worm in the wheel frame.
Kinematics: worm turned by psi deg about its own axis turns the wheel by -psi * starts / z deg.
"""
from __future__ import annotations

import math

import numpy as np
from shapely.geometry import Point, box as sbox

from . import fits, prim, tf
from .gears import _finish, HF, HA
from .screw import MU_PLA, thread_cs, helix_extrude

WORM_Q = 10.0        # default diameter quotient d1 / m


def worm_pitch_d(m, bore=None, q=WORM_Q):
    """Default worm pitch diameter (mm): q m, enlarged so the root keeps 1.6 mm of wall around the bore."""
    d1 = q * m
    if bore:
        d1 = max(d1, bore + 2 * (HF * m + 1.6))
    return d1


def worm_info(m, d1=None, starts=1, pa=20.0, mu=MU_PLA, bore=None):
    """Worm numbers: pitch (axial, pi m), lead, d1, tip / root diameters, lead angle (deg), friction angle (deg, the
    effective angle of the pa thread atan(mu / cos pa), the one in both efficiencies; friction_angle_axial is
    atan(mu)), self_locking (lead angle <= friction angle, exactly when back_efficiency <= 0), efficiency (worm
    driving) and back_efficiency (wheel driving, <= 0 means it cannot back drive)."""
    d1 = worm_pitch_d(m, bore) if d1 is None else d1
    p = math.pi * m
    lead = p * starts
    gam = math.atan(lead / (math.pi * d1))
    phi = math.atan(mu)
    phin = math.atan(mu / math.cos(math.radians(pa)))
    eff = math.tan(gam) / math.tan(gam + phin)
    back = math.tan(gam - phin) / math.tan(gam)
    return {"m": m, "d1": d1, "starts": starts, "pitch": p, "lead": lead, "d_tip": d1 + 2 * HA * m,
            "d_root": d1 - 2 * HF * m, "lead_angle": math.degrees(gam), "friction_angle": math.degrees(phin),
            "friction_angle_axial": math.degrees(phi), "self_locking": bool(gam <= phin), "efficiency": eff,
            "back_efficiency": back}


def worm_center_distance(m, z, worm_pitch_d, extra=fits.GEAR_CENTER_EXTRA):
    """Worm to wheel centre distance (mm): (d1 + m z) / 2 + extra."""
    return (worm_pitch_d + m * z) / 2 + extra


def _worm_cs(m, d1, starts, pa, thick_extra, ha):
    r1 = d1 / 2
    p = math.pi * m
    ta = math.tan(math.radians(pa))
    w = lambda r: p / 2 + thick_extra - 2 * (r - r1) * ta
    return thread_cs(r1 - HF * m, r1 + ha * m, w, p * starts, starts, n_flank=12)


def worm(m, length, bore=None, d1=None, starts=1, pa=20.0, backlash=fits.GEAR_BACKLASH, chamfer=0.5,
         bore_kind="round", bore_opts=None):
    """Worm (right hand). Frame: axis +Z, z = 0..length. Axial module m, pitch diameter d1 (default worm_pitch_d),
    thread thinned by backlash / 2 at d1, tip d1 + 2 m, root d1 - 2.5 m. chamfer bevels the tip at both ends."""
    from .gears import cut_bore, tip_chamfer
    d1 = worm_pitch_d(m, bore) if d1 is None else d1
    cs = _worm_cs(m, d1, starts, pa, -backlash / 2, HA)
    body = helix_extrude(cs, length, math.pi * m * starts)
    body = tip_chamfer(body, d1 / 2 + HA * m, length, chamfer)
    if bore:
        body = cut_bore(body, bore, bore_kind, -1, length + 1, **(bore_opts or {}))
    return body


def worm_pose(m, z, worm_pitch_d, face, worm_length, psi=0.0, extra=fits.GEAR_CENTER_EXTRA):
    """4x4 placing a worm (its own frame, z = 0..worm_length) in the wheel frame: worm axis along +Y through
    (a, 0, face / 2), centred on y = 0, turned psi deg about its own axis. Mesh phase: wheel at -psi * starts / z deg.
    worm_length should be an odd multiple of the pitch for a single start (lead + even multiple of the pitch in
    general) so the nominal phase lines up; otherwise add 360 * (worm_length / 2 - lead / 2) / lead to psi."""
    a = worm_center_distance(m, z, worm_pitch_d, extra)
    return tf.mul(tf.T(a, 0, face / 2), tf.Rx(-90), tf.T(0, 0, -worm_length / 2), tf.Rz(psi))


def worm_wheel(m, z, face, worm_pitch_d, starts=1, pa=20.0, backlash=fits.GEAR_BACKLASH, throated=True,
               bore=None, bore_kind="round", bore_opts=None, hub=None, steps_per_pitch=6):
    """Worm wheel for worm(m, ..., d1=worm_pitch_d, starts). Frame: axis +Z, face z = 0..face, a tooth space on +X.
    Throated: concave rim of radius d1 / 2 - m about the worm axis, outer rim radius r2 + 1.5 m; else a cylinder of
    radius r2 + m. Generated by hobbing (exact envelope of the worm). hub (d, h) on top, bore see gears.bore_cs."""
    r1 = worm_pitch_d / 2
    r2 = m * z / 2
    a0 = r1 + r2
    p = math.pi * m
    lead = p * starts
    if throated:
        ro = r2 + 1.5 * m
        rt = r1 - HA * m
        prof = sbox(0, 0, ro, face).difference(Point(a0, face / 2).buffer(rt, 128))
        if prof.geom_type != "Polygon":
            prof = max(prof.geoms, key=lambda g: g.area)
        blank = prim.revolve(prim.shapely_cs(prof), seg=max(prim.segs(ro), 8 * z))
    else:
        ro = r2 + HA * m
        blank = prim.cyl(ro, face, seg=max(prim.segs(ro), 8 * z))
    # hob: crest 1.25 m (root clearance), thread thickened by backlash / 2, long enough to cross the blank
    rh = r1 + HF * m
    dmin = a0 - rh
    half = math.sqrt(max(ro * ro - dmin * dmin, 0.0)) + p
    n = math.ceil((2 * half / p - starts) / 2)
    L = p * (2 * max(n, 1) + starts)
    hob_cs = _worm_cs(m, worm_pitch_d, starts, pa, backlash / 2, HF)
    pitch_deg = 360.0 / z
    reach = math.degrees(math.acos(min(1.0, dmin / ro))) + 1.0     # angle the hob covers inside the blank
    delta = 0.1 * pitch_deg
    lo, hi = -pitch_deg - delta - reach, delta + reach
    step = pitch_deg / steps_per_pitch
    phis = np.arange(math.floor(lo / step), math.ceil(hi / step) + 1) * step
    # one tooth sector (gap centre to gap centre, plus overlap), cut, then polar copies on a solid core
    r_core = r2 - HF * m - 0.6 * m
    rr = ro + 2
    ts = np.linspace(math.radians(-delta), math.radians(pitch_deg + delta), 16)
    wedge = prim.poly_cs([(0, 0)] + [(rr * math.cos(t), rr * math.sin(t)) for t in ts])
    cutters = []
    for ph in phis:
        # only the stretch of hob that can reach the sector: worm axial y spans x' tan(theta) for x' in [dmin, ro]
        t1 = math.radians(max(-80.0, min(80.0, -2 * delta + ph)))
        t2 = math.radians(max(-80.0, min(80.0, pitch_deg + 2 * delta + ph)))
        y_lo = min(dmin * math.tan(t1), ro * math.tan(t1)) - p / 4
        y_hi = max(dmin * math.tan(t2), ro * math.tan(t2)) + p / 4
        y_lo, y_hi = max(y_lo, -half), min(y_hi, half)
        if y_hi <= y_lo:
            continue
        seg = helix_extrude(hob_cs, y_hi - y_lo, lead, z0=L / 2 + y_lo, step_deg=8.0)
        M = tf.mul(tf.Rz(-ph), worm_pose(m, z, worm_pitch_d, face, L, psi=-ph * z / starts, extra=0.0))
        cutters.append(prim.place(seg, M))
    C = prim.union(cutters)
    sector = prim.extrude(wedge, face + 2, z=-1) - prim.cyl(r_core, face + 4, z=-2, seg=max(prim.segs(r_core), 8 * z))
    piece = (blank ^ sector) - C
    core = blank ^ prim.cyl(r_core + 0.3, face + 4, z=-2, seg=max(prim.segs(r_core), 8 * z))
    body = prim.union([core] + [piece.rotate((0, 0, k * pitch_deg)) for k in range(z)])
    return _finish(body, ro, face, 0.0, hub, bore, bore_kind, bore_opts)
