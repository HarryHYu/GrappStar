"""Run every v31 dart physics case and write the findings list.

  python dart_phys31.py [OUT]   (OUT defaults to out31 when dart-cad has written it, else out30)
  -> OUT/physics.json, OUT/flight_sim.json, OUT/phys31/{anchor,landing,launch_spread}.json + plots, kedge/DART_PHYSICS31.md
"""
import json, math, os, sys, time
import numpy as np
import dart_model as dm
import physics

HERE = os.path.dirname(os.path.abspath(__file__))


def launch_spread(M):
    """Muzzle speed sensitivity at 34 deg: spring rate +-5 percent, rail friction 0.2 to 0.4, dart mass +-5 g."""
    p = dm.base_params(); p.dart.mass = M
    from launcher import launch
    base = float(launch(p, 34.0)["v_muzzle"])
    rows = []
    for name, fn in (("spring k -5 %", lambda q: setattr(q.spring, "k", q.spring.k * 0.95)), ("spring k +5 %", lambda q: setattr(q.spring, "k", q.spring.k * 1.05)),
                     ("rail mu 0.2", lambda q: q.launch.__setitem__("mu_rail", 0.2)), ("rail mu 0.4", lambda q: q.launch.__setitem__("mu_rail", 0.4)),
                     ("dart -5 g", lambda q: setattr(q.dart, "mass", M - 0.005)), ("dart +5 g", lambda q: setattr(q.dart, "mass", M + 0.005))):
        q = dm.base_params(); q.dart.mass = M
        try:
            fn(q)
            v = float(launch(q, 34.0)["v_muzzle"])
        except Exception as e:
            v = float("nan")
        rows.append((name, round(v, 3), round((v - base) / base * 100, 2)))
    half = [abs(r[2]) for r in rows if r[2] == r[2]]
    sig = math.sqrt(sum(((a + b) / 2) ** 2 for a, b in zip(half[0::2], half[1::2]))) / 2   # each range taken as +-2 sigma
    return dict(v_base=round(base, 3), rows=rows, sigma_percent=round(sig, 2), note="each listed range is taken as +-2 sigma, combined root-sum-square")


def fmt(x, n=1):
    return f"{x:.{n}f}"


def main(out=None):
    out = dm.out_dir(out)
    t0 = time.time()
    R = physics.run(out)
    ph = os.path.join(out, "phys31")
    A = json.load(open(os.path.join(ph, "anchor.json"))); L = json.load(open(os.path.join(ph, "landing.json")))
    F = json.load(open(os.path.join(out, "flight_sim.json")))
    S = launch_spread(R["mass_g"] / 1000)
    json.dump(S, open(os.path.join(ph, "launch_spread.json"), "w"), indent=1)
    write_md(out, R, A, L, F, S)
    print(f"done in {time.time() - t0:.0f} s: {out}/physics.json, {ph}, {HERE}/DART_PHYSICS31.md")


